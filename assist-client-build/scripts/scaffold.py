#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
scaffold.py - instantiate a complete, buildable project from a template.

Templates carry {{PLACEHOLDER}} markers. Values come from a JSON offset table
produced during the research phase, so the source tree is generated by this
script rather than authored from scratch.

Usage:
  python scaffold.py --list
  python scaffold.py --template android-overlay --out ./myproj
  python scaffold.py --template android-overlay --out ./myproj --config offsets.json
  python scaffold.py --template android-overlay --out ./myproj --device /dev/kmem_dev
"""

import argparse
import json
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TEMPLATE_ROOT = os.path.join(os.path.dirname(HERE), "templates")

DEFAULTS = {
    "DEVICE": "/dev/kmem_hub",
    "MODULE_BASE": "0",
    "MATRIX_OFF": "0",
    "ENTITY_BASE": "0",
    "STRIDE": "0",
    "COUNT": "0",
    "POS_OFF": "0",
    "HEALTH_OFF": "0",
    "TEAM_OFF": "0",
    "BOX_RATIO": "0.5",
    "HEIGHT": "1.8",
}

TEXT_EXT = {
    ".java", ".kt", ".c", ".h", ".cpp", ".hpp", ".gradle", ".xml", ".md",
    ".py", ".json", ".properties", ".txt", ".pro", ".cmake",
}

PLACEHOLDER_RE = re.compile(r"\{\{([A-Z0-9_]+)\}\}")


def list_templates():
    if not os.path.isdir(TEMPLATE_ROOT):
        print("[!] no templates directory: %s" % TEMPLATE_ROOT)
        return []
    names = []
    for entry in sorted(os.listdir(TEMPLATE_ROOT)):
        path = os.path.join(TEMPLATE_ROOT, entry)
        if os.path.isdir(path):
            names.append(entry)
    return names


def describe_template(name):
    readme = os.path.join(TEMPLATE_ROOT, name, "README.md")
    if not os.path.exists(readme):
        return ""
    with open(readme, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#"):
                return line[:100]
    return ""


def render_tree(src, dst, values):
    rendered = 0
    copied = 0
    leftover = set()

    for root, dirs, files in os.walk(src):
        dirs[:] = [d for d in dirs if d not in ("__pycache__", ".git", "build")]
        rel = os.path.relpath(root, src)
        target = os.path.join(dst, rel) if rel != "." else dst
        os.makedirs(target, exist_ok=True)

        for fn in files:
            s = os.path.join(root, fn)
            d = os.path.join(target, fn)
            ext = os.path.splitext(fn)[1].lower()

            if ext not in TEXT_EXT:
                shutil.copy2(s, d)
                copied += 1
                continue

            try:
                with open(s, "r", encoding="utf-8") as f:
                    text = f.read()
            except (UnicodeDecodeError, OSError):
                shutil.copy2(s, d)
                copied += 1
                continue

            for key, val in values.items():
                text = text.replace("{{%s}}" % key, str(val))

            for m in PLACEHOLDER_RE.finditer(text):
                leftover.add(m.group(1))

            with open(d, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            rendered += 1

    return rendered, copied, sorted(leftover)


def cmd_list(a):
    names = list_templates()
    if not names:
        print("no templates available")
        return 1
    print("available templates:")
    for n in names:
        desc = describe_template(n)
        print("  %-20s %s" % (n, desc))
    return 0


def cmd_build(a):
    src = os.path.join(TEMPLATE_ROOT, a.template)
    if not os.path.isdir(src):
        print("[!] unknown template: %s" % a.template)
        print("[i] run --list to see available templates")
        return 1

    values = dict(DEFAULTS)
    if a.device:
        values["DEVICE"] = a.device

    if a.config:
        if not os.path.exists(a.config):
            print("[!] config not found: %s" % a.config)
            return 1
        with open(a.config, "r", encoding="utf-8") as f:
            try:
                cfg = json.load(f)
            except json.JSONDecodeError as e:
                print("[!] bad JSON in %s: %s" % (a.config, e))
                return 1
        if not isinstance(cfg, dict):
            print("[!] config must be a JSON object")
            return 1
        for k, v in cfg.items():
            values[str(k).upper()] = v

    out = os.path.abspath(a.out)
    if os.path.exists(out) and os.listdir(out) and not a.force:
        print("[!] output directory is not empty: %s" % out)
        print("[i] use --force to overwrite")
        return 1

    os.makedirs(out, exist_ok=True)
    rendered, copied, leftover = render_tree(src, out, values)

    print("[+] template : %s" % a.template)
    print("[+] output   : %s" % out)
    print("[+] files    : %d rendered, %d copied" % (rendered, copied))
    print("[+] config   : %s" % (a.config if a.config else "defaults"))

    if leftover:
        print("[!] unsubstituted placeholders: %s" % ", ".join(leftover))
        print("[i] supply them via --config, or edit the generated sources")
        return 1

    print("")
    print("next:")
    print("  cd %s" % out)
    print("  ./gradlew assembleDebug      (gradlew.bat on Windows)")
    print("")
    print("offsets applied:")
    for k in ("MODULE_BASE", "MATRIX_OFF", "ENTITY_BASE", "STRIDE", "COUNT",
              "POS_OFF", "HEALTH_OFF", "TEAM_OFF"):
        print("  %-12s %s" % (k, values.get(k)))
    return 0


def build_parser():
    p = argparse.ArgumentParser(description="instantiate a buildable project from a template")
    p.add_argument("--list", action="store_true", help="list available templates")
    p.add_argument("--template", "-t")
    p.add_argument("--out", "-o", help="output directory")
    p.add_argument("--config", "-c", help="JSON file with offset values")
    p.add_argument("--device", help="kernel device path override")
    p.add_argument("--force", action="store_true", help="write into a non-empty directory")
    return p


def main(argv=None):
    args = build_parser().parse_args(argv)
    if args.list:
        return cmd_list(args)
    if not args.template or not args.out:
        print("[!] --template and --out are required (or use --list)")
        return 1
    return cmd_build(args)


if __name__ == "__main__":
    sys.exit(main())
